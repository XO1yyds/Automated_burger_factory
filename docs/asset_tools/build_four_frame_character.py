def rgba(path):
 im=Image.open(ROOT/path).convert('RGBA');a=im.getchannel('A');im.putalpha(a.point(lambda x:0 if x<=3 else x));return im
def extract(spec):
 im=rgba(spec['source'])
 if 'cell' in spec:
  i=spec['cell'];im=im.crop((round(i*im.width/4),0,round((i+1)*im.width/4),im.height))
 elif 'rect' in spec:im=im.crop(tuple(spec['rect']))
 if spec.get('normalized'):return im.resize((256,256),Image.Resampling.LANCZOS)
 bounds=im.getchannel('A').point(lambda a:255 if a>=24 else 0).getbbox()
 if not bounds:raise ValueError('empty source '+str(spec))
 # Complete-pose fit only: no head/eye/limb cutouts, mirroring or deformation.
 art=im.crop(bounds);scale=min(230/art.height,240/art.width)
 art=art.resize((round(art.width*scale),round(art.height*scale)),Image.Resampling.LANCZOS)
 result=Image.new('RGBA',(256,256));result.alpha_composite(art,(round(128-art.width/2),248-art.height));return result
def socket(im,d):
 if d=='back':return [.5,.625]
 points=[]
 for y in range(130,193):
  for x in range(30,226):
   r,g,b,a=im.getpixel((x,y))
   side=(d=='front' and 77<x<179) or (d=='left' and x<135) or (d=='right' and x>121)
   if side and a>180 and r>180 and 85<g<225 and 55<b<205 and r>g*1.06 and g>b*1.02:points.append((x,y))
 if len(points)<8:return [{'front':.5,'left':.30,'right':.70}[d],.635]
 return [round(sum(x for x,y in points)/len(points)/256,5),round(sum(y for x,y in points)/len(points)/256,5)]
for row,d in enumerate(['front','left','right','back']):
 for col,a in enumerate(fps):
  key=f'{d}_{a}';entry=next(e for e in old['entries'] if e['id']==key)
  spec=selected.get(key)
  if not spec:
   meta=json.loads((ROOT/'assets'/entry['runtime256']['config']).read_text(encoding='utf-8'))
   indexes=[0,1,2,3] if len(meta['frames'])==4 else [0,3,6,9] if len(meta['frames'])==12 else [0,2,4,6]
   sources=[]
   for i in indexes:
    r=meta['frames'][i]['frame'];sources.append({'source':'assets/'+entry['runtime256']['atlas'],'rect':[r['x'],r['y'],r['x']+r['w'],r['y']+r['h']],'normalized':True,'original_index':i})
   spec={'frames':sources,'art_review':'pending' if a in ('walk','run','carry_walk','carry_run') else 'whole_pose_reuse_reviewed',
         'provenance':'existing_complete_pose_catalog; historical status retained in original catalog'}
  assert len(spec['frames'])==4
  frames=[extract(f) for f in spec['frames']]
  folder=RUNTIME/key;folder.mkdir(exist_ok=True)
  atlas=Image.new('RGBA',(1088,272));sockets=[];hashes=[];bounds=[]
  for i,im in enumerate(frames):
   # Hidden RGB is not visible artwork; canonicalize it for atlas identity and clean filtering.
   im.paste((0,0,0,0),(0,0,256,256),im.getchannel('A').point(lambda a:255 if a==0 else 0))
   im.save(folder/f'{i+1}.png');atlas.alpha_composite(im,(i*272+8,8));sockets.append(socket(im,d))
   hashes.append(hashlib.sha256(im.tobytes()).hexdigest());bounds.append(im.getchannel('A').point(lambda x:255 if x>=24 else 0).getbbox())
  atlas.save(RUNTIME/f'{key}.png')
  frames[0].save(folder/'preview.webp',save_all=True,append_images=frames[1:],duration=round(1000/fps[a]),loop=0,lossless=True)
  frames[0].save(folder/'preview.gif',save_all=True,append_images=frames[1:],duration=round(1000/fps[a]),loop=0,disposal=2)
  atlas_path=(RUNTIME/f'{key}.png').relative_to(ROOT/'assets').as_posix()
  record={'id':key,'direction':d,'action':a,'frames':4,'fps':fps[a],'loop':a!='think','atlas':atlas_path,
          'source_selection':spec,'sockets':sockets,'frame_hashes':hashes,'unique_frames':len(set(hashes)),
          'bounds':bounds,'pivot':[.5,.96875],'complete_pose_only':True,'head_eye_local_edit':False,
          'runtime_config':'Factory/CharacterFrames.lua','art_review':spec['art_review']}
  entries.append(record)
  lua.append(f" ['{key}']={{atlas='{atlas_path}',sockets={{{','.join('{'+str(s[0])+','+str(s[1])+'}' for s in sockets)}}}}},")
lua.append('}')
